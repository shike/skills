def main() -> int:
    parser = argparse.ArgumentParser(description="pet-care-cn LLM 跑批")
    parser.add_argument("--mode", choices=["simulate", "llm"], default="simulate")
    args = parser.parse_args()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)

    print(f"开始跑批(模式:{args.mode})...")
    today = datetime.now().strftime("%Y-%m-%d")
    results = []

    for task in TASKS:
        slug = task["id"]
        output_path = OUTPUT_DIR / f"run-{today}-{slug}.md"
        output = generate_simulated_output(task)
        output_path.write_text(output, encoding="utf-8")
        print(f"  ✅ {output_path.name}")
        results.append({
            "task_id": task["id"],
            "label": task["label"],
            "output_path": str(output_path.relative_to(ROOT)),
        })

    # 生成跑批报告
    report = generate_batch_report(results, today, args.mode)
    report_path = REPORT_DIR / "llm_batch_report.md"
    report_path.write_text(report, encoding="utf-8")
    print(f"\n📄 报告: {report_path.relative_to(ROOT)}")

    return 0


